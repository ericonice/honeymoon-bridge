-- Who was sitting opposite when a field result was made — §1.8a.
--
-- The board already records the computer that *generated* it (`field_boards`), and
-- until now the individual results recorded nothing. That was survivable only while
-- there was exactly one possible answer: `localSession` pins a Doop session to
-- `FIELD_RUNG` and `LATEST_RELEASE`, so every result so far was made against
-- Championship v3.
--
-- **`LATEST_RELEASE` is the part that moves.** The pin is to whatever the newest
-- release is, not to v3, so shipping a v4 changes the Doop opposition for everybody
-- with nothing anywhere saying so — and §1.8a's central rule is that the opposition
-- is fixed, because a score says as much about who sat opposite as about who made it.
-- Recorded here, a field can be read per opposition instead of silently mixing two.
--
-- **Null's meaning is settled by `opponent_account_id` rather than being ambiguous.**
-- Where an opponent account is named, a person sat opposite and there was no computer
-- to have a version: null means *no computer*. Where it is absent, the computer sat
-- opposite and null means *not recorded* — a row written before this migration, the
-- same reading `results.bot_version` already carries for the games that predate it.
ALTER TABLE field_results ADD COLUMN bot_version INTEGER;
ALTER TABLE field_results ADD COLUMN difficulty TEXT;

-- The generated rows are backfilled exactly rather than assumed: a board stores the
-- configuration it was generated by, and a generated result is that generation. So
-- this is copying a recorded fact across, not guessing at one.
--
-- Human rows are deliberately left null. What a person played against is not written
-- down anywhere the server can reach, and `FIELD_RUNG` being a constant today is a
-- fact about the client's source rather than about those rows. Null reads as "against
-- the computer, configuration not recorded", which is true.
UPDATE field_results
   SET bot_version = (SELECT bot_version FROM field_boards WHERE field_boards.id = field_results.board_id),
       difficulty  = (SELECT difficulty  FROM field_boards WHERE field_boards.id = field_results.board_id)
 WHERE generated = 1;

-- Reading a field per opposition is the query this exists to make cheap.
CREATE INDEX field_results_by_opposition ON field_results(board_id, bot_version, difficulty);
